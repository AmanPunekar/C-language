#include <stdio.h>

int main()
{
    // addition of two numbers

    int a = 10;
    int b = 2;

    int sum = a + b;

    printf("sum of %d and %d is %d\n", a, b, sum);
    printf("subtract of %d and %d is %d\n", a, b, (a-b));
    printf("multiplication of %d and %d is %d\n", a, b, (a*b));
    printf("divide of %d and %d is %d\n", a, b, (a/b));
    

    return 0;
}